/// The root a custom phone host mounts: the app with its packaged theme and
/// id.
///
/// The generated runners build this themselves; the Kotlin and Swift hosts
/// mount the library instead, and both need the theme the app was packaged
/// with set here.
///
/// The id is the GPUI client's: this build replaces it on the same phones, so
/// it has to keep the same application identity the store and the OS know.
#[cfg(any(target_os = "android", target_os = "ios"))]
pub(crate) fn phone_root() -> nsh_core::element::Root {
    nsh_core::element::Root::of::<App>()
        .tokens(
            nsh_base::Theme::from_json(include_str!("../theme.json"))
                .expect("theme.json is generated by gen-theme")
                .into_tokens(),
        )
        .app_id(APP_ID)
}

/// The app's identity: Android's application id and iOS's bundle id.
#[cfg_attr(
    not(any(target_os = "android", target_os = "ios")),
    allow(dead_code, reason = "the phone hosts mount the app by this id")
)]
pub(crate) const APP_ID: &str = "ai.vibex.mobile";

/// The root the Android host mounts.
#[cfg(target_os = "android")]
pub(crate) fn android_root() -> nsh_android::Root {
    phone_root()
}

// Makes this library the Android host's `libnsh.so`: `Native.runRust`
// mounts `App` with its theme.
#[cfg(target_os = "android")]
nsh_android::main!(android_root());

/// Registers the bundled monospace and Nerd Font symbol faces used by the
/// mobile terminal grid so prompts with Powerline / Devicon glyphs render
/// crisply on Android and iOS instead of showing missing-glyph tofu boxes.
fn register_terminal_fonts() {
    static BUNDLED_FONTS: &[&[u8]] = &[
        include_bytes!("../../desktop/assets/fonts/lilex/Lilex-Regular.ttf"),
        include_bytes!("../../desktop/assets/fonts/lilex/Lilex-Bold.ttf"),
        include_bytes!("../../desktop/assets/fonts/nerd-symbols/SymbolsNerdFontMono-Regular.ttf"),
    ];
    spawn(async move {
        let mut loaded = false;
        for &bytes in BUNDLED_FONTS {
            if register_font(bytes.to_vec()).await.is_ok() {
                loaded = true;
            }
        }
        if loaded {
            vibex_nsh_ui::screens::terminal::notify_terminal_fonts_ready();
        }
    });
}

/// The app's UI set (`nsh.json` `"rust"`).
#[native_module("vibex/native")]
fn native(registry: &mut Registry) {
    registry.register::<App>();
}

/// The app's root: pairing while no runtime is connected, the session shell
/// once one is.
///
/// The pairing service, the settings and the session service are made once,
/// outside the UI's reactive regions: a reconnection or a language change must
/// not build a second store or a second event stream. An effect owns the
/// session service's lifetime, and a dynamic region rebuilds the surface when
/// the language changes, because the copy is resolved while the tree is built.
#[component]
pub fn App() -> impl IntoElement {
    // The app's own data directory. A host that keeps no files for the app
    // (the web) gets a temporary one, so the page still works there.
    let data = data_dir().unwrap_or_else(|| std::env::temp_dir().join("vibex-mobile-nsh"));
    // `nsh` writes `<support>/<app id>`, but this build replaces the GPUI
    // client in place and keeps the files it left one or two levels up. The
    // imports below look there too, and skip themselves once the new store
    // has a value.
    migration::migrate_drafts(&data);
    let pairing = PairingService::new(data.clone());
    host::start(pairing.clone());
    let settings = SettingsState::new(&data);
    settings.apply();
    register_terminal_fonts();

    let connected = pairing.connected();
    let switcher = pairing.switcher();
    let settings_open = signal(false);
    let settings_page = signal(SettingsPage::Root);
    let services = signal_with(None::<Rc<SessionService>>, SignalEquals::Never);
    let service_error = signal(None::<SharedString>);
    let boot_connection = signal(ConnectionState::Connecting);
    let attempt = signal(0u64);

    install_service_effect(
        pairing.clone(),
        settings_open,
        settings_page,
        services,
        service_error,
        boot_connection,
        attempt,
    );
    start_host_poller(services);
    on_back_press({
        let pairing = pairing.clone();
        move || {
            if settings_open.get_untracked() {
                if settings_page.get_untracked() == SettingsPage::Root {
                    settings_open.set(false);
                } else {
                    settings_page.set(SettingsPage::Root);
                }
            } else if pairing.overlay_open() {
                pairing.close_overlay();
            } else if pairing.switcher().get_untracked() {
                pairing.close_switcher();
            } else {
                return session_screen::handle_back();
            }
            true
        }
    });

    let open_settings: Rc<dyn Fn()> = {
        let open = settings_open;
        let page = settings_page;
        Rc::new(move || {
            page.set(SettingsPage::Root);
            open.set(true);
        })
    };
    let settings_host = settings_host(&pairing, &settings, settings_open, settings_page, services);

    // A screen is what carries a status-bar setting, and a screen lives in a
    // stack. The bar's glyphs follow the appearance the app is drawn in rather
    // than the system's: `nsh.json` leaves the app following the system, and a
    // phone in dark mode drew white glyphs over this app's light page.
    let bar = move || nsh_core::StatusBarSetting {
        style: Some(if nsh_core::element::dark() {
            nsh_core::StatusBarStyle::Light
        } else {
            nsh_core::StatusBarStyle::Dark
        }),
        hidden: None,
        animated: None,
    };
    stack().flex_1().child(
        screen()
            .status_bar(bar)
            // The app draws its own bars, so the screen's native header is not
            // shown: left on, it took a bar's height plus the status bar's at
            // the top of every page and the app's own content started below it.
            .header_visible(false)
            .flex_1()
            .relative()
            .bg(|| vibex_nsh_ui::theme::block_page())
            .child(dynamic({
                let pairing = pairing.clone();
                let settings = settings.clone();
                let open_settings = open_settings.clone();
                move || {
                    // The copy is read while the tree is built, so the language is
                    // a rebuild of the surface rather than a value looked up per
                    // frame.
                    let _ = settings.revision.get();
                    root_view(
                        pairing.clone(),
                        open_settings.clone(),
                        services,
                        service_error,
                        boot_connection,
                        attempt,
                        settings_host.clone(),
                    )
                }
            })),
    )
}

/// Builds the surface for the current connection, language and switcher state.
#[allow(clippy::too_many_arguments)]
fn root_view(
    pairing: PairingService,
    open_settings: Rc<dyn Fn()>,
    services: Signal<Option<Rc<SessionService>>>,
    service_error: Signal<Option<SharedString>>,
    boot_connection: Signal<ConnectionState>,
    attempt: Signal<u64>,
    settings_host: SettingsHost,
) -> AnyElement {
    let connected = pairing.connected();
    let switcher = pairing.switcher();
    let mut pairing_host = pairing.host();
    pairing_host.on_open_settings = open_settings.clone();
    let switcher_host = pairing_host.clone();
    let connecting_actions = {
        let pairing = pairing.clone();
        let retry = attempt;
        (
            Rc::new(move || {
                retry.update(|attempt| *attempt = attempt.wrapping_add(1));
            }) as Rc<dyn Fn()>,
            {
                let pairing = pairing.clone();
                Rc::new(move || pairing.open_switcher()) as Rc<dyn Fn()>
            },
            {
                let pairing = pairing.clone();
                Rc::new(move || pairing.disconnect()) as Rc<dyn Fn()>
            },
        )
    };

    view()
        .flex_1()
        .relative()
        .child(when(move || connected.get().is_none(), {
            let pairing_host = pairing_host.clone();
            move || pairing_screen::pairing(pairing_host.clone()).into_element()
        }))
        .child(dynamic({
            let connecting_actions = connecting_actions.clone();
            move || {
                let Some(runtime) = connected.get() else {
                    return view().into_element();
                };
                let service = services.get();
                match service {
                    Some(service) if service.host_id() == runtime.bundle.host_id() => {
                        session_screen::session(service.host()).into_element()
                    }
                    _ => connecting_screen::connecting(ConnectingHost {
                        state: boot_connection,
                        error: service_error,
                        on_retry: connecting_actions.0.clone(),
                        on_switch_runtime: connecting_actions.1.clone(),
                        on_disconnect: connecting_actions.2.clone(),
                    })
                    .into_element(),
                }
            }
        }))
        .child(when(move || switcher.get() && connected.get().is_some(), {
            let switcher_host = switcher_host.clone();
            move || {
                view()
                    .absolute()
                    .top_0()
                    .left_0()
                    .w_full()
                    .h_full()
                    .bg(vibex_nsh_ui::theme::block_page)
                    .child(pairing_screen::pairing(switcher_host.clone()))
                    .into_element()
            }
        }))
        .child(settings_screen::settings(settings_host))
        .into_element()
}

/// Builds the settings sheet's host from the app's stores.
fn settings_host(
    pairing: &PairingService,
    settings: &SettingsState,
    open: Signal<bool>,
    page: Signal<SettingsPage>,
    services: Signal<Option<Rc<SessionService>>>,
) -> SettingsHost {
    let appearance = settings.appearance;
    let language = settings.language;
    let haptics = settings.haptics;
    let keep_screen_on = settings.keep_screen_on;
    let font_scale = settings.font_scale;
    let reduce_motion = settings.reduce_motion;
    let notifications = settings.notifications;
    let notify_completed = settings.notify_completed;
    let notify_needs_input = settings.notify_needs_input;
    let notify_failed = settings.notify_failed;
    let show_token_usage = settings.show_token_usage;
    let show_plan_goal = settings.show_plan_goal;
    let show_generation_status = settings.show_generation_status;
    let show_reasoning = settings.show_reasoning;
    let auto_continue = settings.auto_continue;
    let settings_for_appearance = settings.clone();
    let settings_for_language = settings.clone();
    let settings_for_haptics = settings.clone();
    let settings_for_screen = settings.clone();
    let settings_for_text = settings.clone();
    let settings_for_motion = settings.clone();
    let settings_for_notifications = settings.clone();
    let settings_for_completed = settings.clone();
    let settings_for_needs_input = settings.clone();
    let settings_for_failed = settings.clone();
    let settings_for_token = settings.clone();
    let settings_for_plan = settings.clone();
    let settings_for_generation = settings.clone();
    let settings_for_reasoning = settings.clone();
    let settings_for_auto_continue = settings.clone();
    let services_for_token = services;
    let services_for_plan = services;
    let services_for_generation = services;
    let services_for_reasoning = services;
    let services_for_auto_continue = services;
    let pairing_for_disconnect = pairing.clone();
    let pairing_for_clear = pairing.clone();
    SettingsHost {
        open,
        page,
        appearance,
        language,
        haptics,
        keep_screen_on,
        font_scale,
        reduce_motion,
        notifications,
        notify_completed,
        notify_needs_input,
        notify_failed,
        show_token_usage,
        show_plan_goal,
        show_generation_status,
        show_reasoning,
        auto_continue,
        runtime: pairing.connected_label(),
        saved: pairing.saved(),
        on_appearance: Rc::new(move |appearance| {
            settings_for_appearance.set_appearance(appearance);
        }),
        on_language: Rc::new(move |language| {
            settings_for_language.set_language(language);
        }),
        on_haptics: Rc::new(move |enabled| {
            settings_for_haptics.set_haptics(enabled);
        }),
        on_keep_screen_on: Rc::new(move |enabled| {
            settings_for_screen.set_keep_screen_on(enabled);
        }),
        on_font_scale: Rc::new(move |percent| {
            settings_for_text.set_font_scale(percent);
        }),
        on_reduce_motion: Rc::new(move |reduce| {
            settings_for_motion.set_reduce_motion(reduce);
        }),
        on_notifications: Rc::new(move |enabled| {
            settings_for_notifications.set_notifications(enabled);
        }),
        on_notify_completed: Rc::new(move |enabled| {
            settings_for_completed.set_notify_completed(enabled);
        }),
        on_notify_needs_input: Rc::new(move |enabled| {
            settings_for_needs_input.set_notify_needs_input(enabled);
        }),
        on_notify_failed: Rc::new(move |enabled| {
            settings_for_failed.set_notify_failed(enabled);
        }),
        on_show_token_usage: Rc::new(move |enabled| {
            settings_for_token.set_show_token_usage(enabled);
            if let Some(service) = services_for_token.get_untracked() {
                service.set_show_token_usage(enabled);
            }
        }),
        on_show_plan_goal: Rc::new(move |enabled| {
            settings_for_plan.set_show_plan_goal(enabled);
            if let Some(service) = services_for_plan.get_untracked() {
                service.set_show_plan_goal(enabled);
            }
        }),
        on_show_generation_status: Rc::new(move |enabled| {
            settings_for_generation.set_show_generation_status(enabled);
            if let Some(service) = services_for_generation.get_untracked() {
                service.set_show_generation_status(enabled);
            }
        }),
        on_show_reasoning: Rc::new(move |enabled| {
            settings_for_reasoning.set_show_reasoning(enabled);
            if let Some(service) = services_for_reasoning.get_untracked() {
                service.set_show_reasoning(enabled);
            }
        }),
        on_install_update: Rc::new(crate::host::request_update_install),
        on_auto_continue: Rc::new(move |enabled| {
            settings_for_auto_continue.set_auto_continue(enabled);
            if let Some(service) = services_for_auto_continue.get_untracked() {
                service.set_auto_continue(enabled);
            }
        }),
        on_disconnect: Rc::new(move || pairing_for_disconnect.disconnect()),
        on_reconnect: Rc::new(move || {
            if let Some(service) = services.get_untracked() {
                service.retry();
            }
        }),
        on_switch_runtime: {
            let pairing = pairing.clone();
            let open = open;
            Rc::new(move || {
                open.set(false);
                pairing.open_switcher();
            })
        },
        on_clear_runtimes: Rc::new(move || pairing_for_clear.clear_runtimes()),
        on_close: { Rc::new(move || open.set(false)) },
    }
}

fn start_host_poller(services: Signal<Option<Rc<SessionService>>>) {
    spawn(async move {
        loop {
            timer(Duration::from_millis(100)).await;
            if let Some(text) = host::take_shared_text()
                && let Some(service) = services.get_untracked()
            {
                service.receive_shared_text(text);
            }
            if let Some(path) = host::take_camera_photo()
                && let Some(service) = services.get_untracked()
            {
                service.attach_camera_photo(path);
            }
            if let Some(reason) = host::take_camera_failure()
                && let Some(service) = services.get_untracked()
            {
                service.camera_failed(reason);
            }
            if host::take_new_session_request()
                && let Some(service) = services.get_untracked()
            {
                service.open_new_session();
            }
        }
    });
}

/// Owns the session service: built once per connected runtime, rebuilt when a
/// connection attempt failed at construction, resumed when the app returns to
/// the foreground.
fn install_service_effect(
    pairing: PairingService,
    settings_open: Signal<bool>,
    settings_page: Signal<SettingsPage>,
    services: Signal<Option<Rc<SessionService>>>,
    service_error: Signal<Option<SharedString>>,
    boot_connection: Signal<ConnectionState>,
    attempt: Signal<u64>,
) {
    let last_attempt = stored(0u64);
    effect(move || {
        let attempt_now = attempt.get();
        let connected = pairing.connected().get();
        let lifecycle_now = lifecycle();
        let existing = services.get_untracked();
        let rebuilt = last_attempt.get() != attempt_now;
        last_attempt.replace(attempt_now);

        let Some(runtime) = connected else {
            if let Some(service) = existing {
                service.shutdown();
                services.set(None);
            }
            host::set_connection_service(false);
            service_error.set(None);
            boot_connection.set(ConnectionState::Connecting);
            return;
        };

        if existing
            .as_ref()
            .is_some_and(|service| service.host_id() == runtime.bundle.host_id())
        {
            if let Some(service) = existing {
                if rebuilt {
                    service.retry();
                } else if lifecycle_now == Lifecycle::Active {
                    service.resume();
                }
            }
            return;
        }

        if let Some(service) = existing {
            service.shutdown();
            services.set(None);
        }
        host::set_connection_service(false);
        service_error.set(None);
        boot_connection.set(ConnectionState::Connecting);

        let disconnect: Rc<dyn Fn()> = {
            let pairing = pairing.clone();
            Rc::new(move || pairing.disconnect())
        };
        let switch_runtime: Rc<dyn Fn()> = {
            let pairing = pairing.clone();
            Rc::new(move || pairing.open_switcher())
        };
        let open_settings: Rc<dyn Fn()> = {
            Rc::new(move || {
                settings_page.set(SettingsPage::Root);
                settings_open.set(true);
            })
        };
        let runtime_renamed: Rc<dyn Fn(&str)> = {
            let pairing = pairing.clone();
            Rc::new(move |name: &str| pairing.rename_connected(name))
        };
        let device_renamed: Rc<dyn Fn(&str)> = {
            let pairing = pairing.clone();
            Rc::new(move |name: &str| pairing.rename_device(name))
        };
        let server_kind: Rc<dyn Fn(vibex_core::RemoteServerKind)> = {
            let pairing = pairing.clone();
            let host_id = runtime.bundle.host_id().to_owned();
            Rc::new(move |kind| pairing.set_host_kind(&host_id, kind))
        };
        // The shell's state must outlive this effect: the effect runs again
        // whenever the connection, the attempt counter or the lifecycle
        // changes, and a signal owned by the scope that created it would be
        // disposed while the service's tasks are still writing it.
        let built = Owner::detached().run(|| {
            SessionService::new(
                &runtime.bundle,
                disconnect,
                switch_runtime,
                open_settings,
                runtime_renamed,
                device_renamed,
                server_kind,
            )
        });
        match built {
            Ok(service) => {
                services.set(Some(Rc::new(service)));
                host::set_connection_service(true);
            }
            Err(error) => {
                service_error.set(Some(pairing::error_text(&error)));
                boot_connection.set(ConnectionState::Offline);
            }
        }
    });
}
