pub fn apply_locale(mode: LocaleMode) -> ResolvedLocale {
    let locale = resolve_locale(mode, system_locale());
    CURRENT_LOCALE.store(locale.code(), Ordering::Relaxed);
    gpui_component::set_locale(locale.tag());
    locale
}

/// The locale the workbench is currently rendering in.
///
/// Reads the value [`apply_locale`] stored; the system tag is not re-parsed on
/// every lookup.
pub fn current_locale() -> ResolvedLocale {
    ResolvedLocale::from_code(CURRENT_LOCALE.load(Ordering::Relaxed))
}

/// The process-wide locale in the shared, platform-neutral form.
///
/// The desktop's snapshot carries a few strings the shared table cannot know
/// about, but a split or a phrase that every native client must draw the same
/// way lives on [`SharedLocale`] so no client owns a second copy of it. This is
/// the bridge between the desktop's own resolved locale and that table.
pub fn shared_locale() -> SharedLocale {
    current_locale().shared()
}

/// The resolved locale expressed as the preference a dialog can hold.
///
/// A component that resolves its own strings from a [`LocaleMode`] — the
/// directory picker does — needs the mode that is in force, and the resolved
/// locale is the only thing this module keeps.
pub fn current_locale_mode() -> LocaleMode {
    match current_locale() {
        ResolvedLocale::En => LocaleMode::En,
        ResolvedLocale::ZhCn => LocaleMode::ZhCn,
        ResolvedLocale::ZhTw => LocaleMode::ZhTw,
        ResolvedLocale::Ja => LocaleMode::Ja,
        ResolvedLocale::Ko => LocaleMode::Ko,
        ResolvedLocale::De => LocaleMode::De,
        ResolvedLocale::Fr => LocaleMode::Fr,
        ResolvedLocale::Es => LocaleMode::Es,
        ResolvedLocale::PtBr => LocaleMode::PtBr,
        ResolvedLocale::Ru => LocaleMode::Ru,
    }
}

pub fn current_strings() -> &'static Strings {
    strings(current_locale())
}

pub fn text_for(
    locale: ResolvedLocale,
    en: &'static str,
    zh_cn: &'static str,
    zh_tw: &'static str,
) -> &'static str {
    match locale {
        ResolvedLocale::En => en,
        ResolvedLocale::ZhCn => zh_cn,
        ResolvedLocale::ZhTw => zh_tw,
        // The added languages carry no argument at the call site: their copy is
        // keyed by the English sentence in the shared table.
        other => vibex_ui::locale_copy::localized(other.shared(), en),
    }
}

pub fn text(en: &'static str, zh_cn: &'static str, zh_tw: &'static str) -> &'static str {
    text_for(current_locale(), en, zh_cn, zh_tw)
}

/// The runtime's own name for an Agent account, said in the reader's language.
///
/// The runtime writes one account label for every client, and writes it in
/// English, because an Agent account is the product's own concept rather than a
/// name the reader chose. A stored label keeps whatever the runtime wrote when
/// the turn ran — including the wording it used before the account was renamed
/// — and this is what turns either into the reader's name. Anything that is not
/// the runtime's wording, such as a Provider Profile's own name, is returned
/// exactly as written, and the account hint behind the name is kept.
pub fn agent_account_display_label(label: &str) -> String {
    let account = text("Agent account", "Agent 账户", "Agent 帳戶");
    match vibex_core::agent_account_label_hint(label) {
        Some("") => account.to_string(),
        Some(hint) => format!("{account} - {hint}"),
        None => label.to_string(),
    }
}

