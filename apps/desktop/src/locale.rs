pub fn resolve_locale(mode: LocaleMode, system_locale: Option<&str>) -> ResolvedLocale {
    match mode {
        LocaleMode::En => ResolvedLocale::En,
        LocaleMode::ZhCn => ResolvedLocale::ZhCn,
        LocaleMode::ZhTw => ResolvedLocale::ZhTw,
        LocaleMode::Ja => ResolvedLocale::Ja,
        LocaleMode::Ko => ResolvedLocale::Ko,
        LocaleMode::De => ResolvedLocale::De,
        LocaleMode::Fr => ResolvedLocale::Fr,
        LocaleMode::Es => ResolvedLocale::Es,
        LocaleMode::PtBr => ResolvedLocale::PtBr,
        LocaleMode::Ru => ResolvedLocale::Ru,
        LocaleMode::System => {
            ResolvedLocale::from_shared(SharedLocale::from_system_tag(system_locale))
        }
    }
}

/// The copy table for `locale`.
///
/// One static per language: the table is a few kilobytes of `&'static str`
/// fields, and the renderer reads it many times per frame, so it is never
/// rebuilt or copied — callers borrow the table for the process lifetime.
pub fn strings(locale: ResolvedLocale) -> &'static Strings {
    match locale {
        ResolvedLocale::En => &STRINGS_EN,
        ResolvedLocale::ZhCn => &STRINGS_ZH_CN,
        ResolvedLocale::ZhTw => &STRINGS_ZH_TW,
        ResolvedLocale::Ja => &STRINGS_JA,
        ResolvedLocale::Ko => &STRINGS_KO,
        ResolvedLocale::De => &STRINGS_DE,
        ResolvedLocale::Fr => &STRINGS_FR,
        ResolvedLocale::Es => &STRINGS_ES,
        ResolvedLocale::PtBr => &STRINGS_PT_BR,
        ResolvedLocale::Ru => &STRINGS_RU,
    }
}

