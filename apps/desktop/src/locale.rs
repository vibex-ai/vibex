#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ResolvedLocale {
    En,
    ZhCn,
    ZhTw,
    Ja,
    Ko,
    De,
    Fr,
    Es,
    PtBr,
    Ru,
}

impl ResolvedLocale {
    /// Every locale the application ships, in the order the language picker
    /// lists them.
    pub const ALL: [ResolvedLocale; 10] = [
        Self::En,
        Self::ZhCn,
        Self::ZhTw,
        Self::Ja,
        Self::Ko,
        Self::De,
        Self::Fr,
        Self::Es,
        Self::PtBr,
        Self::Ru,
    ];

    pub const fn tag(self) -> &'static str {
        match self {
            Self::En => "en",
            Self::ZhCn => "zh-CN",
            Self::ZhTw => "zh-TW",
            Self::Ja => "ja",
            Self::Ko => "ko",
            Self::De => "de",
            Self::Fr => "fr",
            Self::Es => "es",
            Self::PtBr => "pt-BR",
            Self::Ru => "ru",
        }
    }

    /// The desktop's locale for a shared one.
    pub const fn from_shared(locale: SharedLocale) -> Self {
        match locale {
            SharedLocale::En => Self::En,
            SharedLocale::ZhCn => Self::ZhCn,
            SharedLocale::ZhTw => Self::ZhTw,
            SharedLocale::Ja => Self::Ja,
            SharedLocale::Ko => Self::Ko,
            SharedLocale::De => Self::De,
            SharedLocale::Fr => Self::Fr,
            SharedLocale::Es => Self::Es,
            SharedLocale::PtBr => Self::PtBr,
            SharedLocale::Ru => Self::Ru,
        }
    }

    /// The platform-neutral locale the shared UI copy resolves through.
    pub const fn shared(self) -> SharedLocale {
        match self {
            Self::En => SharedLocale::En,
            Self::ZhCn => SharedLocale::ZhCn,
            Self::ZhTw => SharedLocale::ZhTw,
            Self::Ja => SharedLocale::Ja,
            Self::Ko => SharedLocale::Ko,
            Self::De => SharedLocale::De,
            Self::Fr => SharedLocale::Fr,
            Self::Es => SharedLocale::Es,
            Self::PtBr => SharedLocale::PtBr,
            Self::Ru => SharedLocale::Ru,
        }
    }

    /// Compact code for the resolved-locale cache.
    const fn code(self) -> u8 {
        match self {
            Self::En => 0,
            Self::ZhCn => 1,
            Self::ZhTw => 2,
            Self::Ja => 3,
            Self::Ko => 4,
            Self::De => 5,
            Self::Fr => 6,
            Self::Es => 7,
            Self::PtBr => 8,
            Self::Ru => 9,
        }
    }

    const fn from_code(code: u8) -> Self {
        match code {
            1 => Self::ZhCn,
            2 => Self::ZhTw,
            3 => Self::Ja,
            4 => Self::Ko,
            5 => Self::De,
            6 => Self::Fr,
            7 => Self::Es,
            8 => Self::PtBr,
            9 => Self::Ru,
            _ => Self::En,
        }
    }
}

