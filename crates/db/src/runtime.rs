    pub fn list_non_terminal(conn: &Connection) -> VibexResult<Vec<MessageSubmissionRecord>> {
        let mut stmt = conn
            .prepare(&format!(
                "SELECT {} FROM agent_message_submissions s
                 JOIN agent_message_submission_payloads p
                   ON p.payload_reference = s.message_payload_reference
                 WHERE s.status NOT IN (?1, ?2, ?3, ?4)
                 ORDER BY s.session_id ASC, p.submission_sequence ASC",
                Self::COLUMNS
            ))
            .map_err(storage_err(
                "message_submission_list_failed",
                "failed to prepare durable message submission scan",
            ))?;
        let rows = stmt
            .query_map(
                params![
                    enum_to_db(&MessageSubmissionStatus::Completed)?,
                    enum_to_db(&MessageSubmissionStatus::Failed)?,
                    enum_to_db(&MessageSubmissionStatus::Cancelled)?,
                    enum_to_db(&MessageSubmissionStatus::AmbiguousPromptDispatch)?,
                ],
                Self::read_row,
            )
            .map_err(storage_err(
                "message_submission_list_failed",
                "failed to query durable message submissions",
            ))?;
        let mut records = Vec::new();
        for row in rows {
            records.push(Self::decode_row(row.map_err(storage_err(
                "message_submission_decode_failed",
                "failed to decode durable message submission",
            ))?)?);
        }
        Ok(records)
    }

