    /// Advances the submission status with a CAS on the expected current
    /// status. Illegal transitions per §20.4 are rejected before touching the
    /// database.
    pub fn advance_status(
        conn: &Connection,
        submission_id: &MessageSubmissionId,
        from: MessageSubmissionStatus,
        to: MessageSubmissionStatus,
    ) -> VibexResult<()> {
        if !from.can_transition_to(to) {
            return Err(VibexError::validation(
                "message_submission_illegal_transition",
                "message submission status transition is not allowed",
            ));
        }
        let now = unix_timestamp_ms();
        let dispatched_at_ms = (to == MessageSubmissionStatus::Dispatched).then_some(now);
        let changed = conn
            .execute(
                "UPDATE agent_message_submissions
                 SET status = ?2,
                     dispatched_at_ms = COALESCE(?3, dispatched_at_ms),
                     updated_at_ms = ?4
                 WHERE submission_id = ?1 AND status = ?5",
                params![
                    submission_id.as_str(),
                    enum_to_db(&to)?,
                    dispatched_at_ms,
                    now,
                    enum_to_db(&from)?,
                ],
            )
            .map_err(storage_err(
                "message_submission_update_failed",
                "failed to update message submission status",
            ))?;
        if changed == 0 {
            return Err(cas_conflict(
                "message_submission_status_conflict",
                "message submission is not in the expected status",
            ));
        }
        Ok(())
    }

