    fn get_latest_for_selection_revision_tx(
        conn: &Connection,
        session_id: &VibexSessionId,
        selection_revision: i64,
        non_terminal_only: bool,
    ) -> VibexResult<Option<RuntimeSwitchRecord>> {
        let (sql, terminal_params) = if non_terminal_only {
            (
                format!(
                    "SELECT {} FROM runtime_switches
                     WHERE session_id = ?1 AND desired_selection_revision = ?2
                       AND status NOT IN (?3, ?4, ?5, ?6, ?7)
                     ORDER BY created_at_ms DESC, switch_id DESC LIMIT 1",
                    Self::COLUMNS
                ),
                Some([
                    RuntimeSwitchStatus::Committed,
                    RuntimeSwitchStatus::Failed,
                    RuntimeSwitchStatus::Cancelled,
                    RuntimeSwitchStatus::Superseded,
                    RuntimeSwitchStatus::AmbiguousExternalEffect,
                ]),
            )
        } else {
            (
                format!(
                    "SELECT {} FROM runtime_switches
                     WHERE session_id = ?1 AND desired_selection_revision = ?2
                     ORDER BY created_at_ms DESC, switch_id DESC LIMIT 1",
                    Self::COLUMNS
                ),
                None,
            )
        };
        let raw = if let Some(statuses) = terminal_params {
            conn.query_row(
                &sql,
                params![
                    session_id.as_str(),
                    selection_revision,
                    enum_to_db(&statuses[0])?,
                    enum_to_db(&statuses[1])?,
                    enum_to_db(&statuses[2])?,
                    enum_to_db(&statuses[3])?,
                    enum_to_db(&statuses[4])?,
                ],
                Self::read_record_row,
            )
            .optional()
        } else {
            conn.query_row(
                &sql,
                params![session_id.as_str(), selection_revision],
                Self::read_record_row,
            )
            .optional()
        }
        .map_err(storage_err(
            "runtime_switch_get_failed",
            "failed to load runtime switch by selection revision",
        ))?;
        raw.map(Self::decode_record).transpose()
    }

    /// Claims a product-level Requested intent only after the previous pending
    /// switch has released the session slot. Selection supersession is handled
    /// before source/pending checks so an old queued intent cannot block newer
    /// user intent.
    pub fn claim_requested(
        conn: &mut Connection,
        switch_id: &RuntimeSwitchId,
    ) -> VibexResult<RequestedSwitchClaimOutcome> {
        let tx = conn.transaction().map_err(storage_err(
            "runtime_switch_requested_claim_transaction_failed",
            "failed to start requested runtime switch claim transaction",
        ))?;
        let record = Self::get(&tx, switch_id)?.ok_or_else(|| {
            VibexError::validation("runtime_switch_not_found", "runtime switch was not found")
        })?;
        if record.status == RuntimeSwitchStatus::Superseded {
            return Ok(RequestedSwitchClaimOutcome::Superseded);
        }
        if record.status != RuntimeSwitchStatus::Requested {
            return Ok(RequestedSwitchClaimOutcome::Claimed);
        }

        let session: Option<(i64, i64, Option<String>, Option<String>)> = tx
            .query_row(
                "SELECT revision, selection_revision, current_binding_id, pending_switch_id
                 FROM agent_sessions WHERE session_id = ?1 AND deleted_at_ms IS NULL",
                params![record.session_id.as_str()],
                |row| Ok((row.get(0)?, row.get(1)?, row.get(2)?, row.get(3)?)),
            )
            .optional()
            .map_err(storage_err(
                "runtime_switch_requested_claim_failed",
                "failed to load session for requested runtime switch claim",
            ))?;
        let Some((revision, selection_revision, current_binding_id, pending_switch_id)) = session
        else {
            return Err(VibexError::validation(
                "session_not_found",
                "Agent session was not found",
            ));
        };
        let now = unix_timestamp_ms();
        if selection_revision != record.desired_selection_revision {
            let changed = tx
                .execute(
                    "UPDATE runtime_switches SET status = ?2, updated_at_ms = ?3
                     WHERE switch_id = ?1 AND status = ?4",
                    params![
                        switch_id.as_str(),
                        enum_to_db(&RuntimeSwitchStatus::Superseded)?,
                        now,
                        enum_to_db(&RuntimeSwitchStatus::Requested)?,
                    ],
                )
                .map_err(storage_err(
                    "runtime_switch_requested_claim_failed",
                    "failed to supersede stale requested runtime switch",
                ))?;
            if changed != 1 {
                return Err(cas_conflict(
                    "runtime_switch_status_conflict",
                    "runtime switch changed while its requested state was being claimed",
                ));
            }
            RuntimeSwitchEventRepository::append_tx(
                &tx,
                switch_id,
                &record.session_id,
                RuntimeSwitchEventKind::RuntimeSwitchSuperseded,
                RuntimeSwitchStatus::Superseded,
                None,
                now,
            )?;
            tx.commit().map_err(storage_err(
                "runtime_switch_requested_claim_transaction_failed",
                "failed to commit requested runtime switch supersession",
            ))?;
            return Ok(RequestedSwitchClaimOutcome::Superseded);
        }
        if revision != record.source_revision
            || current_binding_id.as_deref()
                != record.source_binding_id.as_ref().map(|id| id.as_str())
        {
            return Err(cas_conflict(
                "runtime_switch_source_conflict",
                "requested runtime switch source state changed before it could be claimed",
            ));
        }
        if pending_switch_id
            .as_deref()
            .is_some_and(|pending| pending != switch_id.as_str())
        {
            tx.commit().map_err(storage_err(
                "runtime_switch_requested_claim_transaction_failed",
                "failed to finish waiting requested runtime switch claim",
            ))?;
            return Ok(RequestedSwitchClaimOutcome::WaitingForPending);
        }

        let claimed_session = tx
            .execute(
                "UPDATE agent_sessions SET pending_switch_id = ?2, updated_at_ms = ?3
                 WHERE session_id = ?1 AND revision = ?4 AND selection_revision = ?5
                   AND (current_binding_id IS ?6)
                   AND (pending_switch_id IS NULL OR pending_switch_id = ?2)
                   AND deleted_at_ms IS NULL",
                params![
                    record.session_id.as_str(),
                    switch_id.as_str(),
                    now,
                    record.source_revision,
                    record.desired_selection_revision,
                    record.source_binding_id.as_ref().map(|id| id.as_str()),
                ],
            )
            .map_err(storage_err(
                "runtime_switch_requested_claim_failed",
                "failed to claim session pending slot for requested runtime switch",
            ))?;
        let claimed_switch = tx
            .execute(
                "UPDATE runtime_switches SET status = ?2, updated_at_ms = ?3
                 WHERE switch_id = ?1 AND status = ?4",
                params![
                    switch_id.as_str(),
                    enum_to_db(&RuntimeSwitchStatus::Reserved)?,
                    now,
                    enum_to_db(&RuntimeSwitchStatus::Requested)?,
                ],
            )
            .map_err(storage_err(
                "runtime_switch_requested_claim_failed",
                "failed to reserve requested runtime switch",
            ))?;
        if claimed_session != 1 || claimed_switch != 1 {
            return Err(cas_conflict(
                "runtime_switch_requested_claim_conflict",
                "requested runtime switch changed while claiming the pending slot",
            ));
        }
        tx.commit().map_err(storage_err(
            "runtime_switch_requested_claim_transaction_failed",
            "failed to commit requested runtime switch claim",
        ))?;
        Ok(RequestedSwitchClaimOutcome::Claimed)
    }

    /// §17 — advances the switch status with a CAS on the expected current
    /// status. Illegal state-machine moves are rejected before any SQL runs;
    /// a stale expected status surfaces as a structured CAS conflict.
    pub fn advance_status(
        conn: &Connection,
        switch_id: &RuntimeSwitchId,
        expected: RuntimeSwitchStatus,
        next: RuntimeSwitchStatus,
    ) -> VibexResult<()> {
        if !expected.can_transition_to(next) {
            return Err(VibexError::validation(
                "runtime_switch_transition_invalid",
                "runtime switch status transition is not allowed",
            ));
        }
        let tx = conn.unchecked_transaction().map_err(storage_err(
            "runtime_switch_advance_transaction_failed",
            "failed to start runtime switch advance transaction",
        ))?;
        let now = unix_timestamp_ms();
        let changed = tx
            .execute(
                "UPDATE runtime_switches
                 SET status = ?2, updated_at_ms = ?3
                 WHERE switch_id = ?1 AND status = ?4",
                params![
                    switch_id.as_str(),
                    enum_to_db(&next)?,
                    now,
                    enum_to_db(&expected)?,
                ],
            )
            .map_err(storage_err(
                "runtime_switch_advance_failed",
                "failed to advance runtime switch status",
            ))?;
        if changed == 0 {
            return Err(cas_conflict(
                "runtime_switch_status_conflict",
                "runtime switch is not in the expected status",
            ));
        }
        if next == RuntimeSwitchStatus::Prepared {
            let session_id: String = tx
                .query_row(
                    "SELECT session_id FROM runtime_switches WHERE switch_id = ?1",
                    params![switch_id.as_str()],
                    |row| row.get(0),
                )
                .map_err(storage_err(
                    "runtime_switch_advance_failed",
                    "failed to load runtime switch session for event projection",
                ))?;
            RuntimeSwitchEventRepository::append_tx(
                &tx,
                switch_id,
                &parse_id(session_id, VibexSessionId::parse)?,
                RuntimeSwitchEventKind::RuntimeSwitchPrepared,
                next,
                None,
                now,
            )?;
        }
        tx.commit().map_err(storage_err(
            "runtime_switch_advance_transaction_failed",
            "failed to commit runtime switch advance transaction",
        ))
    }

    /// Finalizes the stable target binding while a newly reserved switch has
    /// not performed any external operation. This is used to select the
    /// source binding for LiveMutation after the reserve CAS succeeds.
    pub fn compare_and_set_target_binding(
        conn: &Connection,
        switch_id: &RuntimeSwitchId,
        expected: Option<&RuntimeBindingId>,
        next: &RuntimeBindingId,
    ) -> VibexResult<()> {
        let changed = conn
            .execute(
                "UPDATE runtime_switches
                 SET target_binding_id = ?2, updated_at_ms = ?3
                 WHERE switch_id = ?1 AND status = ?4 AND target_binding_id IS ?5",
                params![
                    switch_id.as_str(),
                    next.as_str(),
                    unix_timestamp_ms(),
                    enum_to_db(&RuntimeSwitchStatus::Reserved)?,
                    expected.map(|id| id.as_str()),
                ],
            )
            .map_err(storage_err(
                "runtime_switch_target_binding_update_failed",
                "failed to finalize runtime switch target binding",
            ))?;
        if changed == 0 {
            return Err(cas_conflict(
                "runtime_switch_target_binding_conflict",
                "runtime switch target binding changed concurrently",
            ));
        }
        Ok(())
    }

