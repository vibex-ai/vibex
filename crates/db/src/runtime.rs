    /// Stores a structured restore result behind exact switch identity and
    /// status/revision/previous-value predicates.
    pub fn compare_and_set_restore_compatibility_result(
        conn: &Connection,
        switch_id: &RuntimeSwitchId,
        session_id: &VibexSessionId,
        expected_source_revision: i64,
        expected_status: RuntimeSwitchStatus,
        expected_result: Option<&AgentSessionRestoreResult>,
        next_result: &AgentSessionRestoreResult,
    ) -> VibexResult<()> {
        let expected_json = expected_result.map(json_to_db).transpose()?;
        let next_json = json_to_db(next_result)?;
        let changed = conn
            .execute(
                "UPDATE runtime_switches
                 SET restore_compatibility_result_json = ?2, updated_at_ms = ?3
                 WHERE switch_id = ?1 AND session_id = ?4 AND source_revision = ?5
                   AND status = ?6 AND restore_compatibility_result_json IS ?7",
                params![
                    switch_id.as_str(),
                    next_json,
                    unix_timestamp_ms(),
                    session_id.as_str(),
                    expected_source_revision,
                    enum_to_db(&expected_status)?,
                    expected_json,
                ],
            )
            .map_err(storage_err(
                "runtime_switch_restore_result_update_failed",
                "failed to update runtime switch restore result",
            ))?;
        if changed == 1 {
            return Ok(());
        }
        Err(cas_conflict(
            "runtime_switch_restore_result_cas_conflict",
            "runtime switch restore result is stale",
        ))
    }

    fn finish_without_commit(
        conn: &mut Connection,
        session_id: &VibexSessionId,
        switch_id: &RuntimeSwitchId,
        status: RuntimeSwitchStatus,
        error_code: Option<&str>,
        error_detail_redacted: Option<&str>,
    ) -> VibexResult<()> {
        if error_code.is_some_and(|code| {
            code.trim().is_empty()
                || code.len() > MAX_RUNTIME_SELECTION_ERROR_CODE_LEN
                || code.chars().any(|character| character.is_control())
        }) {
            return Err(VibexError::validation(
                "runtime_selection_error_code_invalid",
                "runtime selection error code must be non-empty, bounded and contain no control characters",
            ));
        }
        let tx = conn.transaction().map_err(storage_err(
            "runtime_switch_finish_transaction_failed",
            "failed to start runtime switch finish transaction",
        ))?;
        let current_raw: Option<(String, String, i64)> = tx
            .query_row(
                "SELECT status, session_id, desired_selection_revision
                 FROM runtime_switches WHERE switch_id = ?1",
                params![switch_id.as_str()],
                |row| Ok((row.get(0)?, row.get(1)?, row.get(2)?)),
            )
            .optional()
            .map_err(storage_err(
                "runtime_switch_finish_failed",
                "failed to load runtime switch status",
            ))?;
        let Some((current_raw, stored_session_id, desired_selection_revision)) = current_raw else {
            return Err(VibexError::validation(
                "runtime_switch_not_found",
                "runtime switch was not found",
            ));
        };
        if stored_session_id != session_id.as_str() {
            return Err(VibexError::conflict(
                "runtime_switch_session_mismatch",
                "runtime switch does not belong to the requested session",
            ));
        }
        let current: RuntimeSwitchStatus = enum_from_db(current_raw)?;
        if current != status && !current.can_transition_to(status) {
            return Err(VibexError::conflict(
                "runtime_switch_finish_conflict",
                "runtime switch cannot be finished from its current status",
            ));
        }
        let now = unix_timestamp_ms();
        if current != status {
            let changed = tx
                .execute(
                    "UPDATE runtime_switches
                 SET status = ?2, error_code = COALESCE(?3, error_code),
                     error_detail_redacted = COALESCE(?4, error_detail_redacted),
                     updated_at_ms = ?5
                 WHERE switch_id = ?1 AND status = ?6",
                    params![
                        switch_id.as_str(),
                        enum_to_db(&status)?,
                        error_code,
                        error_detail_redacted,
                        now,
                        enum_to_db(&current)?,
                    ],
                )
                .map_err(storage_err(
                    "runtime_switch_finish_failed",
                    "failed to update runtime switch status",
                ))?;
            if changed == 0 {
                return Err(cas_conflict(
                    "runtime_switch_finish_conflict",
                    "runtime switch status changed while it was being finished",
                ));
            }
        }
        tx.execute(
            "UPDATE agent_sessions
             SET pending_switch_id = NULL, updated_at_ms = ?3
             WHERE session_id = ?1 AND pending_switch_id = ?2",
            params![session_id.as_str(), switch_id.as_str(), now],
        )
        .map_err(storage_err(
            "runtime_switch_finish_failed",
            "failed to clear pending switch",
        ))?;
        match status {
            RuntimeSwitchStatus::Failed | RuntimeSwitchStatus::AmbiguousExternalEffect => {
                tx.execute(
                    "UPDATE agent_sessions
                     SET desired_runtime_selection_json = COALESCE(
                             effective_runtime_selection_json,
                             desired_runtime_selection_json
                         ),
                         runtime_selection_status = ?3,
                         runtime_selection_error_code = ?4,
                         updated_at_ms = ?5
                     WHERE session_id = ?1 AND selection_revision = ?2
                       AND deleted_at_ms IS NULL",
                    params![
                        session_id.as_str(),
                        desired_selection_revision,
                        enum_to_db(&SessionRuntimeSelectionStatus::FailedUsingPrevious)?,
                        error_code,
                        now,
                    ],
                )
                .map_err(storage_err(
                    "runtime_switch_finish_failed",
                    "failed to project runtime switch failure into selection state",
                ))?;
            }
            RuntimeSwitchStatus::Cancelled => {
                tx.execute(
                    "UPDATE agent_sessions
                     SET desired_runtime_selection_json = effective_runtime_selection_json,
                         runtime_selection_status = ?3,
                         runtime_selection_error_code = NULL,
                         updated_at_ms = ?4
                     WHERE session_id = ?1 AND selection_revision = ?2
                       AND deleted_at_ms IS NULL",
                    params![
                        session_id.as_str(),
                        desired_selection_revision,
                        enum_to_db(&SessionRuntimeSelectionStatus::Ready)?,
                        now,
                    ],
                )
                .map_err(storage_err(
                    "runtime_switch_finish_failed",
                    "failed to project runtime switch cancellation into selection state",
                ))?;
            }
            RuntimeSwitchStatus::Superseded => {}
            _ => {
                return Err(VibexError::validation(
                    "runtime_switch_finish_status_invalid",
                    "runtime switch finish status is not terminal without commit",
                ));
            }
        }
        let event_kind = match status {
            RuntimeSwitchStatus::Failed | RuntimeSwitchStatus::AmbiguousExternalEffect => {
                RuntimeSwitchEventKind::RuntimeSwitchFailed
            }
            RuntimeSwitchStatus::Cancelled => RuntimeSwitchEventKind::RuntimeSwitchCancelled,
            RuntimeSwitchStatus::Superseded => RuntimeSwitchEventKind::RuntimeSwitchSuperseded,
            _ => unreachable!("validated terminal status above"),
        };
        RuntimeSwitchEventRepository::append_tx(
            &tx, switch_id, session_id, event_kind, status, error_code, now,
        )?;
        tx.commit().map_err(storage_err(
            "runtime_switch_finish_transaction_failed",
            "failed to commit runtime switch finish transaction",
        ))
    }

