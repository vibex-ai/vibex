fn validate_operation_metadata(request: &SwitchOperationAppendRequest) -> VibexResult<()> {
    if request.operation_kind.is_empty()
        || request.operation_kind.len() > 64
        || !request
            .operation_kind
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'_')
    {
        return Err(VibexError::validation(
            "switch_operation_kind_invalid",
            "switch operation kind must be a bounded snake_case identifier",
        ));
    }
    if request.request_fingerprint.is_empty()
        || request.request_fingerprint.len() > 1024
        || request
            .request_fingerprint
            .chars()
            .any(|character| character.is_control())
    {
        return Err(VibexError::validation(
            "switch_operation_fingerprint_invalid",
            "switch operation request fingerprint must be bounded and contain no control characters",
        ));
    }
    let normalized_fingerprint: String = request
        .request_fingerprint
        .chars()
        .filter(|character| character.is_ascii_alphanumeric())
        .flat_map(char::to_lowercase)
        .collect();
    if [
        "apikey",
        "authtoken",
        "accesstoken",
        "refreshtoken",
        "clientsecret",
        "password",
        "authorization",
        "credential",
        "nativesessionid",
        "resumetoken",
    ]
    .iter()
    .any(|marker| normalized_fingerprint.contains(marker))
    {
        return Err(VibexError::validation(
            "switch_operation_fingerprint_sensitive",
            "switch operation request fingerprint contains forbidden sensitive metadata",
        ));
    }
    if let Some(token) = &request.adapter_idempotency_token
        && (token.is_empty()
            || token.len() > 256
            || token.chars().any(|character| character.is_control()))
    {
        return Err(VibexError::validation(
            "switch_operation_idempotency_token_invalid",
            "switch operation idempotency token must be bounded and contain no control characters",
        ));
    }
    Ok(())
}

