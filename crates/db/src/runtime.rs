/// Decodes an optional typed JSON value from a reserve request before any
/// write happens, so an invalid payload fails with zero side effects.
fn decode_reserve_json<T: serde::de::DeserializeOwned>(
    value: Option<&serde_json::Value>,
    code: &'static str,
    message: &'static str,
) -> VibexResult<Option<T>> {
    value
        .map(|value| serde_json::from_value(value.clone()))
        .transpose()
        .map_err(|_| VibexError::validation(code, message))
}

const RUNTIME_SWITCH_CONFIG_MAX_BYTES: usize = 16 * 1024;

fn validate_bounded_redacted_json(value: &serde_json::Value) -> VibexResult<()> {
    let encoded = serde_json::to_vec(value).map_err(|_| {
        VibexError::validation(
            "runtime_switch_requested_config_invalid",
            "runtime switch requested configuration is not valid JSON",
        )
    })?;
    if encoded.len() > RUNTIME_SWITCH_CONFIG_MAX_BYTES {
        return Err(VibexError::validation(
            "runtime_switch_requested_config_too_large",
            "runtime switch requested configuration exceeds the durable size limit",
        ));
    }
    if json_contains_sensitive_key(value) {
        return Err(VibexError::validation(
            "runtime_switch_requested_config_sensitive",
            "runtime switch requested configuration contains a forbidden sensitive field",
        ));
    }
    Ok(())
}

fn json_contains_sensitive_key(value: &serde_json::Value) -> bool {
    match value {
        serde_json::Value::Object(entries) => entries
            .iter()
            .any(|(key, value)| is_sensitive_config_key(key) || json_contains_sensitive_key(value)),
        serde_json::Value::Array(values) => values.iter().any(json_contains_sensitive_key),
        _ => false,
    }
}

fn is_sensitive_config_key(key: &str) -> bool {
    let normalized: String = key
        .chars()
        .filter(|character| character.is_ascii_alphanumeric())
        .flat_map(char::to_lowercase)
        .collect();
    matches!(
        normalized.as_str(),
        "token"
            | "secret"
            | "password"
            | "authorization"
            | "credential"
            | "credentials"
            | "nativesessionid"
            | "providerresumeidentity"
    ) || normalized.ends_with("apikey")
        || normalized.ends_with("authtoken")
        || normalized.ends_with("accesstoken")
        || normalized.ends_with("refreshtoken")
        || normalized.ends_with("clientsecret")
        || normalized.ends_with("resumetoken")
}

