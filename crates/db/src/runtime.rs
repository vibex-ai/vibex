    #[allow(clippy::too_many_arguments)]
    pub fn record_dispatch_result(
        conn: &mut Connection,
        submission_id: &MessageSubmissionId,
        user_message_timeline_item_id: &TimelineItemId,
        provider_correlation_id: Option<&str>,
        result_first_sequence: i64,
        result_last_sequence: i64,
    ) -> VibexResult<()> {
        if result_first_sequence <= 0 || result_last_sequence < result_first_sequence {
            return Err(VibexError::validation(
                "message_submission_result_range_invalid",
                "message submission result timeline range is invalid",
            ));
        }
        let tx = conn.transaction().map_err(storage_err(
            "message_submission_dispatch_transaction_failed",
            "failed to start message dispatch result transaction",
        ))?;
        let submission_session_id = tx
            .query_row(
                "SELECT session_id FROM agent_message_submissions WHERE submission_id = ?1",
                params![submission_id.as_str()],
                |row| row.get::<_, String>(0),
            )
            .optional()
            .map_err(storage_err(
                "message_submission_dispatch_validation_failed",
                "failed to validate the message dispatch submission",
            ))?
            .ok_or_else(|| {
                VibexError::validation(
                    "message_submission_dispatch_result_invalid",
                    "message dispatch result does not reference an existing submission",
                )
            })?;
        let user_item = tx
            .query_row(
                "SELECT session_id, sequence, kind
                 FROM agent_timeline_items
                 WHERE timeline_item_id = ?1",
                params![user_message_timeline_item_id.as_str()],
                |row| {
                    Ok((
                        row.get::<_, String>(0)?,
                        row.get::<_, i64>(1)?,
                        row.get::<_, String>(2)?,
                    ))
                },
            )
            .optional()
            .map_err(storage_err(
                "message_submission_dispatch_validation_failed",
                "failed to validate the message dispatch Timeline item",
            ))?
            .ok_or_else(|| {
                VibexError::validation(
                    "message_submission_dispatch_result_invalid",
                    "message dispatch result does not reference an existing user Timeline item",
                )
            })?;
        if user_item.0 != submission_session_id
            || user_item.1 < result_first_sequence
            || user_item.1 > result_last_sequence
            || user_item.2 != enum_to_db(&TimelineItemKind::UserMessage)?
        {
            return Err(VibexError::validation(
                "message_submission_dispatch_result_invalid",
                "message dispatch result Timeline item does not match the submission range",
            ));
        }
        let boundary_count = tx
            .query_row(
                "SELECT COUNT(*)
                 FROM agent_timeline_items
                 WHERE session_id = ?1 AND sequence IN (?2, ?3)",
                params![
                    submission_session_id,
                    result_first_sequence,
                    result_last_sequence,
                ],
                |row| row.get::<_, i64>(0),
            )
            .map_err(storage_err(
                "message_submission_dispatch_validation_failed",
                "failed to validate the message dispatch Timeline range",
            ))?;
        let expected_boundary_count = if result_first_sequence == result_last_sequence {
            1
        } else {
            2
        };
        if boundary_count != expected_boundary_count {
            return Err(VibexError::validation(
                "message_submission_dispatch_result_invalid",
                "message dispatch result Timeline range boundaries do not exist",
            ));
        }
        let now = unix_timestamp_ms();
        let payload_changed = tx
            .execute(
                "UPDATE agent_message_submission_payloads
                 SET result_first_sequence = ?2,
                     result_last_sequence = ?3,
                     updated_at_ms = ?4
                 WHERE submission_id = ?1
                   AND result_first_sequence IS NULL
                   AND result_last_sequence IS NULL",
                params![
                    submission_id.as_str(),
                    result_first_sequence,
                    result_last_sequence,
                    now,
                ],
            )
            .map_err(storage_err(
                "message_submission_result_update_failed",
                "failed to persist message dispatch result range",
            ))?;
        let submission_changed = tx
            .execute(
                "UPDATE agent_message_submissions
                 SET status = ?2,
                     user_message_timeline_item_id = ?3,
                     provider_correlation_id = ?4,
                     dispatched_at_ms = ?5,
                     updated_at_ms = ?5
                 WHERE submission_id = ?1 AND status = ?6",
                params![
                    submission_id.as_str(),
                    enum_to_db(&MessageSubmissionStatus::Dispatched)?,
                    user_message_timeline_item_id.as_str(),
                    provider_correlation_id,
                    now,
                    enum_to_db(&MessageSubmissionStatus::AboutToPrompt)?,
                ],
            )
            .map_err(storage_err(
                "message_submission_dispatch_update_failed",
                "failed to persist message dispatch result",
            ))?;
        if payload_changed == 0 || submission_changed == 0 {
            return Err(cas_conflict(
                "message_submission_dispatch_conflict",
                "message submission dispatch result is already recorded or stale",
            ));
        }
        tx.commit().map_err(storage_err(
            "message_submission_dispatch_transaction_failed",
            "failed to commit message dispatch result transaction",
        ))?;
        Ok(())
    }

