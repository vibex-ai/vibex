//! Repositories for the unified ACP runtime hot-switch data model (plan §17/§20).
//!
//! These repositories only provide transactional primitives (insert, CAS
//! updates, journals). The switch business state machine lives elsewhere.
//! All CAS updates are `UPDATE ... WHERE <expected>` guarded and report the
//! number of changed rows; a zero-row update surfaces as a structured
//! `cas_conflict` error instead of panicking or silently succeeding.

